package atividade;

public class Atv3 {
    public static void main(String[] args) {
        System.out.println("--- Números ímpares de 1 a 50:---");
        for(int i=1; i<=51; i+=2){
            System.out.println(i);
        }

        System.out.println("--- Números pares de 1 a 50:---");
        for(int i=2; i<=50; i+=2){
            System.out.println(i);
        }
    }
}
